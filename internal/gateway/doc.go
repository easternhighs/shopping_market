// Package gateway 是这个项目的「统一入口」，也叫 API 网关。
//
// 一句话解释它存在的意义：在微服务里，前端不应该去记「用户服务在哪台机器、
// 秒杀服务在哪台机器」，它只认识一个地址；由这个地址背后的网关负责
// 「这个请求该转给谁」。除此之外，网关还顺手做了几件所有服务都要做的事情。
//
// 网关管四件事：
//  1. 路由（route.go）：路径前缀 → 服务名。表里写的就是「谁归谁管」。
//  2. 鉴权（auth.go）：在最外面把登录令牌验一次，解析出用户 ID，
//     写成请求头传给下游。这样下游服务不用人手一份密钥、也不用每个服务都写一遍解析逻辑。
//  3. 全链路追踪（internal/pkg/trace）：给每个请求发一个编号，一路带着走，方便排查问题。
//  4. 反向代理（proxy.go）：把请求真正转发给对应的服务，并把结果原样带回来。
//
// 为什么现在（阶段 13）就做这件事，而不是等到真拆服务的时候：
// 因为「入口统一」和「真拆进程」是两件独立的事。现在所有服务还在一个进程里，
// 网关只是站在前面替它们收口；等阶段 14 把用户服务拆成独立进程，
// 只需要把路由表里 user 那一行的上游地址换掉，网关的代码不用改。
//
// 这个阶段的网关是「旁路式」的：原来的 cmd/server 一行代码都不用动，
// 网关自己监听另一个端口，把请求转发给它。这么做有三个好处：
//   - 零回归风险：秒杀那条压测过的热路径完全没被碰过；
//   - 演示方便：压测脚本继续直连后端端口（1 万 QPS 的成绩不受这一跳影响），
//     网关那一跳的损耗可以单独测一次、单独报一个数；
//   - 可回退：网关跑不起来也不影响原来的服务，删掉 cmd/gateway 就回到从前。
